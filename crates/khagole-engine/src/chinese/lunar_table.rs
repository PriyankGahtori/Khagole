/// A lunar year of the table.
fn year_at(index: usize) -> LunarYear {
    let (start, mask, leap) = LUNAR_YEARS[index];
    let count = if leap > 0 { 13 } else { 12 };
    LunarYear {
        year: FIRST_YEAR + index as i32,
        start: i64::from(start),
        days: (0..count)
            .map(|i| if mask >> i & 1 == 1 { 30 } else { 29 })
            .collect(),
        leap,
    }
}

/// The lunar date of a Julian day number: (year, month, leap, day), or `None` outside the
/// table.
pub(crate) fn lunar_date_of(day: i64) -> Option<(i32, u8, bool, u8)> {
    let index = LUNAR_YEARS.partition_point(|row| i64::from(row.0) <= day);
    let year = year_at(index.checked_sub(1)?);
    let mut start = year.start;
    let mut number = 0u8;
    for (i, &days) in year.days.iter().enumerate() {
        let leap = year.leap > 0 && i == usize::from(year.leap);
        if !leap {
            number += 1;
        }
        if day < start + i64::from(days) {
            return Some((year.year, number, leap, (day - start + 1) as u8));
        }
        start += i64::from(days);
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::chinese::calendar::lunar_years;

    use crate::test_kernel::full_kernel as kernels;

    #[test]
    #[ignore = "generates the table: cargo test --release print_table -- --ignored --nocapture"]
    fn print_table() {
        let kernels = kernels().expect("kernels/de440s.bsp");
        for year in lunar_years(&kernels, FIRST_YEAR, 2100).unwrap() {
            let mask: u16 = year
                .days
                .iter()
                .enumerate()
                .map(|(i, &d)| u16::from(d == 30) << i)
                .sum();
            println!(
                "    ({}, 0b{:013b}, {}), // {}",
                year.start, mask, year.leap, year.year
            );
        }
    }

    #[test]
    fn the_table_matches_the_calendar() {
        let Some(kernels) = kernels() else { return };
        let last = FIRST_YEAR + LUNAR_YEARS.len() as i32 - 1;
        let computed = lunar_years(&kernels, FIRST_YEAR, last).unwrap();
        for (i, year) in computed.iter().enumerate() {
            assert_eq!(&year_at(i), year);
        }
        assert_eq!(LUNAR_YEARS.len(), 201);
    }

    #[test]
    fn lunar_dates() {
        // 2020-01-25 (JDN 2458874) is the New Year of 2020; 2023-04-10 is the 20th of the
        // leap second month.
        assert_eq!(lunar_date_of(2_458_874), Some((2020, 1, false, 1)));
        assert_eq!(lunar_date_of(2_460_045), Some((2023, 2, true, 20)));
        assert_eq!(lunar_date_of(2_400_000), None);
    }
}
